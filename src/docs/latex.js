// LaTeX compatibility catalog.
//
// This is a translation reference for the standard LaTeX/AMS mathematical
// vocabulary, not a claim that every glyph in the 604-page Comprehensive
// LaTeX Symbol List has a native MathScript construct. Package fonts, emoji,
// phonetics, and decorative text glyphs are outside the language's scope.
//
// Every row says what MathScript can actually do:
//   native      exact MathScript equivalent
//   approximate same meaning with a different rendering or spelling
//   none        no native equivalent in this version

import { GREEK_DOCS } from "./greek.js";
import { SYMBOL_DOCS } from "./symbols.js";

const L = String.raw;

function row(category, latex, mathscript, status = "native", target = null, note = "") {
  return { category, latex, mathscript, status, target, note };
}

function none(category, latex, note = "No native MathScript equivalent.") {
  return row(category, latex, null, "none", null, note);
}

function unsupported(category, names, note) {
  return names.map((name) => none(category, `\\${name}`, note));
}

